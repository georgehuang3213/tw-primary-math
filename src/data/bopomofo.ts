export function parseToBopomofoChars(rawText: string): CharWithBpmf[] {
  if (!rawText) return [];
  const results: CharWithBpmf[] = [];
  const regex = /\[([^\]|]+)\|([^\]]+)\]|([^\[]+)/g;
  let match;

  const phraseKeys = Object.keys(COMPOUND_PHRASE_DICT).sort((a, b) => b.length - a.length);

  while ((match = regex.exec(rawText)) !== null) {
    if (match[1] && match[2]) {
      const chars = match[1].split('');
      const bpmfs = match[2].trim().split(/\s+/);
      if (chars.length === bpmfs.length) {
        chars.forEach((c, i) => {
          results.push({
            char: c,
            bpmf: bpmfs[i],
            isChinese: /[\u4e00-\u9fa5]/.test(c)
          });
        });
      } else {
        chars.forEach((c, i) => {
          results.push({
            char: c,
            bpmf: bpmfs[i] || getCharBpmf(c),
            isChinese: /[\u4e00-\u9fa5]/.test(c)
          });
        });
      }
    } else if (match[3]) {
      const textChunk = match[3];
      let pos = 0;

      while (pos < textChunk.length) {
        let matchedPhrase = false;

        // 1. 優先匹配多字詞彙片語（例如「數數看」ㄕㄨˇ ㄕㄨˇ ㄎㄢˋ、「數字」ㄕㄨˋ ㄗˋ）
        for (const phrase of phraseKeys) {
          if (textChunk.startsWith(phrase, pos)) {
            const bpmfs = COMPOUND_PHRASE_DICT[phrase];
            for (let pi = 0; pi < phrase.length; pi++) {
              results.push({
                char: phrase[pi],
                bpmf: bpmfs[pi],
                isChinese: true
              });
            }
            pos += phrase.length;
            matchedPhrase = true;
            break;
          }
        }

        // 2. 單字解析（正確處理 UTF-16 surrogate pairs 表情符號，避免出現菱形問號亂碼）
        if (!matchedPhrase) {
          const codePoint = textChunk.codePointAt(pos)!;
          const charLength = codePoint > 0xffff ? 2 : 1;
          const c = textChunk.slice(pos, pos + charLength);
          const isChinese = /[\u4e00-\u9fa5]/.test(c);
          results.push({
            char: c,
            bpmf: isChinese ? getCharBpmf(c) : undefined,
            isChinese
          });
          pos += charLength;
        }
      }
    }
  }

  return results;
}
